// Writes STORYBOARD.md from the shot lists the renderer actually uses, so the two cannot drift.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const edit = process.env.FILM_EDIT;
const locked = edit === "locked" || edit === "ink"; // same table shape
const { build, shotList } = await import(edit === "ink" ? "../ink/film.mjs" : edit === "locked" ? "../locked/film.mjs" : "./film.mjs");

const here = dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(readFileSync(join(here, "../../out/voice/higgsfield/segments-fixed-point.json"), "utf8")).segments;
const clock = (s) => `${Math.floor(s / 60)}:${(s % 60).toFixed(2).padStart(5, "0")}`;
const cell = (s) => String(s ?? "").replaceAll("|", "/").replaceAll("\n", " ");
let md = "# Storyboard\n\nGenerated by `motion/storyboard.mjs` from the shot lists the renderer uses. Output times are in the final cut. Caption area is the bottom ink band in every shot. Source times are seconds in the phone recording or the selected desktop take (`main`).\n";
for (const key of ["film", "x"]) {
  md += `\n## ${key === "film" ? "Hackathon film, 180.000 s" : "X launch film, 44.600 s"}\n`;
  let start = 0;
  for (const [i, scene] of build(key).entries()) {
    const seg = manifest[`${key}-${i}`];
    md += `\n### ${scene.name}: ${clock(start)} to ${clock(start + scene.dur)}. Voice from ${clock(start + seg.offset)} to ${clock(start + seg.offset + seg.duration)}\n\n> ${seg.transcript}\n\n| Output | Type | Source | Takeaway | ${locked ? "" : "Composition | Motion | "}Disclosure | Transition out |\n| --- | --- | --- | --- | ${locked ? "" : "--- | --- | "}--- | --- |\n`;
    for (const s of shotList(key).filter((x) => x.scene === scene.name)) md += `| ${clock(start + s.start)} to ${clock(start + s.end)} | ${cell(s.kind)} | ${cell(s.source)} | ${cell(s.takeaway)} | ${locked ? "" : `${cell(s.composition)} | ${cell(s.motion)} | `}${cell(s.disclosure)} | ${cell(s.transition)} |\n`;
    start += scene.dur;
  }
}
writeFileSync(join(here, edit === "ink" ? "../STORYBOARD-INK.md" : edit === "locked" ? "../STORYBOARD-LOCKED.md" : "../STORYBOARD.md"), md);
console.log("STORYBOARD.md written");
